import type { Schema, SchemaField } from "../types.js";

function tsType(field: SchemaField): string {
  switch (field.type) {
    case "uuid":
    case "string":
    case "date":
    case "datetime":
    case "image":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "enum":
      return (field.values ?? []).map((v) => JSON.stringify(v)).join(" | ") || "string";
    case "ref":
      return field.ref ?? "string";
    case "array":
      return field.ref ? `${field.ref}[]` : "string[]";
    default:
      return "string";
  }
}

/**
 * Gera types.ts: enum vira union literal, BRL vira number (PRD-05 RF-04).
 * Deve compilar com tsc --noEmit sem ajustes.
 */
export function buildTypes(schemas: Schema[]): string {
  const blocks = schemas.map((s) => {
    const lines = s.fields.map((f) => `  ${f.name}${f.required ? "" : "?"}: ${tsType(f)};`);
    return `export interface ${s.name} {\n${lines.join("\n")}\n}`;
  });
  return `// Generated by DevMock — do not edit by hand.\n\n${blocks.join("\n\n")}\n`;
}
