import { plural } from "../mock/routes.js";
import type { Schema } from "../types.js";
import { fieldToJsonSchema } from "./jsonschema.js";

interface OpenApiDoc {
  openapi: string;
  info: { title: string; version: string; description: string };
  paths: Record<string, unknown>;
  components: { schemas: Record<string, unknown> };
}

/**
 * Gera OpenAPI 3.0 válido a partir dos Schemas (PRD-05 RF-02).
 * Deve passar em swagger-parser sem erros (aceite).
 */
export function buildOpenApi(schemas: Schema[], title = "DevMock API"): OpenApiDoc {
  const paths: Record<string, unknown> = {};
  const components: Record<string, unknown> = {};

  for (const s of schemas) {
    const base = `/${plural(s.name)}`;
    const ref = { $ref: `#/components/schemas/${s.name}` };
    const required = s.fields.filter((f) => f.required).map((f) => f.name);
    const properties: Record<string, unknown> = {};
    for (const f of s.fields) properties[f.name] = fieldToJsonSchema(f);
    components[s.name] = {
      type: "object",
      properties,
      ...(required.length > 0 ? { required } : {}),
    };

    paths[base] = {
      get: {
        summary: `Returns a list of ${s.name}.`,
        parameters: [
          { name: "page", in: "query", schema: { type: "integer", minimum: 1 } },
          { name: "limit", in: "query", schema: { type: "integer", minimum: 1 } },
        ],
        responses: {
          "200": {
            description: `Returns a list of ${s.name}.`,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    data: { type: "array", items: ref },
                    total: { type: "integer" },
                    page: { type: "integer" },
                    limit: { type: "integer" },
                  },
                },
              },
            },
          },
        },
      },
      post: {
        summary: `Creates a ${s.name}.`,
        requestBody: {
          content: { "application/json": { schema: ref } },
        },
        responses: {
          "201": {
            description: `${s.name} created.`,
            content: { "application/json": { schema: ref } },
          },
        },
      },
    };
    paths[`${base}/{id}`] = {
      get: {
        summary: `Returns a ${s.name} by id.`,
        parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
        responses: {
          "200": {
            description: `${s.name} found.`,
            content: { "application/json": { schema: ref } },
          },
          "404": { description: "Not found." },
        },
      },
      delete: {
        summary: `Deletes a ${s.name}.`,
        parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
        responses: { "204": { description: "Deleted." } },
      },
    };
  }

  return {
    openapi: "3.0.3",
    info: { title, version: "1.0.0", description: "Generated by DevMock — Schema is the source of truth." },
    paths,
    components: { schemas: components },
  };
}
